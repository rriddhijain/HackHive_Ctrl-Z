// Generates src/styles/theme.css (committed, so the build never needs this library): `npm run theme`.
// M3 colour roles from seed #1A73E8, SchemeContent, spec 2021, contrast 0 (DESIGN §4.2), for dark (default)
// and light; the fixed severity palette (§4.4, not from the seed) with error roles mapped onto it; state-layer
// opacities (§4.5); and the type scale as Tailwind @theme text utilities (§3.2).
import { registerHooks } from "node:module";

// The library's ESM build imports "./x" without ".js", which Node's resolver rejects: retry with ".js".
registerHooks({
  resolve(spec, ctx, next) {
    try { return next(spec, ctx); } catch (e) { if (spec.startsWith(".")) return next(spec + ".js", ctx); throw e; }
  },
});
const { Hct, argbFromHex, hexFromArgb, SchemeContent, MaterialDynamicColors: M } = await import("@material/material-color-utilities");

const ROLES = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
  "primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "secondaryFixed", "secondaryFixedDim", "onSecondaryFixed", "onSecondaryFixedVariant",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed", "onTertiaryFixedVariant",
  "surface", "surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
  "surfaceContainerHigh", "surfaceContainerHighest", "onSurface", "onSurfaceVariant", "surfaceVariant",
  "outline", "outlineVariant", "inverseSurface", "inverseOnSurface", "scrim", "shadow", "surfaceTint"];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

// Google red / yellow / green families; vivid fills in both themes (captain rejected muted red).
const SEV = {
  light: {
    critical: "#D93025", "on-critical": "#FFFFFF", "critical-container": "#FCE8E6", "on-critical-container": "#A50E0E", "critical-text": "#C5221F",
    high: "#F9AB00", "on-high": "#202124", "high-container": "#FEF7E0", "on-high-container": "#8C4A00", "high-text": "#8C4A00",
    ok: "#188038", "on-ok": "#FFFFFF", "ok-dot": "#1E8E3E", "ok-container": "#E6F4EA", "on-ok-container": "#0D652D", "ok-text": "#137333",
  },
  dark: {
    critical: "#D93025", "on-critical": "#FFFFFF", "critical-container": "#4A1512", "on-critical-container": "#F6AEA9", "critical-text": "#F28B82",
    high: "#F9AB00", "on-high": "#202124", "high-container": "#3D2E00", "on-high-container": "#FDD663", "high-text": "#FDD663",
    ok: "#188038", "on-ok": "#FFFFFF", "ok-dot": "#81C995", "ok-container": "#0F3D1E", "on-ok-container": "#A8DAB5", "ok-text": "#81C995",
  },
};

// [size px, line px, weight, tracking px, em weight, em tracking px]
const TYPE = {
  "display-l": [57, 64, 400, -0.2, 500, 0], "display-m": [45, 52, 400, 0, 500, 0], "display-s": [36, 44, 400, 0, 500, 0],
  "headline-l": [32, 40, 400, 0, 500, 0], "headline-m": [28, 36, 400, 0, 500, 0], "headline-s": [24, 32, 400, 0, 500, 0],
  "title-l": [22, 28, 400, 0, 500, 0], "title-m": [16, 24, 500, 0.2, 700, 0.15], "title-s": [14, 20, 500, 0.1, 700, 0.1],
  "body-l": [16, 24, 400, 0.5, 500, 0.15], "body-m": [14, 20, 400, 0.2, 500, 0.25], "body-s": [12, 16, 400, 0.4, 500, 0.4],
  "label-l": [14, 20, 500, 0.1, 700, 0.1], "label-m": [12, 16, 500, 0.5, 700, 0.5], "label-s": [11, 16, 500, 0.5, 700, 0.5],
};

const seed = Hct.fromInt(argbFromHex("#1A73E8"));
const block = (dark) => {
  const s = new SchemeContent(seed, dark, 0, "2021");
  const sev = SEV[dark ? "dark" : "light"];
  const lines = ROLES.map((r) => {
    if (!M[r]) throw new Error("missing role " + r);
    return `  --md-sys-color-${kebab(r)}: ${hexFromArgb(M[r].getArgb(s)).toUpperCase()};`;
  });
  lines.push(...Object.entries(sev).map(([k, x]) => `  --hh-${k}: ${x};`));
  // One red in the product: error roles are the critical palette.
  lines.push(`  --md-sys-color-error: var(--hh-critical-text);`, `  --md-sys-color-on-error: ${dark ? "#601410" : "#FFFFFF"};`,
    `  --md-sys-color-error-container: var(--hh-critical-container);`, `  --md-sys-color-on-error-container: var(--hh-on-critical-container);`);
  lines.push(`  --icon-grad: ${dark ? -25 : 0};`);
  return lines.join("\n");
};

const px = (x) => `${x / 16}rem`;
const type = Object.entries(TYPE).flatMap(([k, [sz, lh, w, tr, ew, etr]]) => [
  `  --text-${k}: ${px(sz)}; --text-${k}--line-height: ${px(lh)}; --text-${k}--letter-spacing: ${tr}px; --text-${k}--font-weight: ${w};`,
  `  --text-${k}-em: ${px(sz)}; --text-${k}-em--line-height: ${px(lh)}; --text-${k}-em--letter-spacing: ${etr}px; --text-${k}-em--font-weight: ${ew};`,
]).join("\n");

console.log(`/* GENERATED by scripts/gen-theme.mjs (npm run theme). Do not edit by hand. */
/* Seed #1A73E8 · SchemeContent · spec 2021 · contrast 0. Dark is the default; light via data-theme="light". */
:root, :root[data-theme="dark"] {
  color-scheme: dark;
${block(true)}
}
:root[data-theme="light"] {
  color-scheme: light;
${block(false)}
}
:root {
  /* State layers (androidx StateTokens) */
  --state-hover: 0.08; --state-focus: 0.1; --state-pressed: 0.1; --state-dragged: 0.16;
  --state-disabled-container: 0.12; --state-disabled-content: 0.38;
}

@theme {
  --text-*: initial; /* only the M3 type scale exists */
${type}
}`);
